import pandas as pd
import glob
from subprocess import call

def create_bash_script_parse_hhbrepid(workdir_path, ecf_env_path):
    """Create bash script to run hhrepid output parsing in a parallel manner.

    Parameters:
    -----------
    workdir_path : string
        Path to the working directory.
    ecf_env_path : string
        Path to virtualenv where ecf-explorer code is stored. It needs to be
        communicated to the script to activate virtualenv in bash script.

    Returns:
    --------
    string
        Absolute path to the created bash script.
    """
    script_filepath = workdir_path + '/ecf-explorer/scripts/' \
    + 'run_parse_hhrepid.sh'

    cmd = '#!/bin/bash\n\n'
    cmd += 'FILE=$(basename "${1}")\nFILE=${FILE%.*}\n'
    cmd += 'source ' + ecf_env_path + '/bin/activate\n'
    cmd += 'python3 ' + ecf_env_path \
    + '/ecf-explorer/src/annot/parse_hhrepid_file.py ${1}\n'

    with open(script_filepath, 'w') as file_sh:
        file_sh.write(cmd)

    return script_filepath

def run_parsing_hhrepid_with_bash(workdir_path, n_cores):
    """Run previously prepared bash script that will run parsing on all files
    generated by hhrepid in a parallel manner.

    Parameters:
    -----------
    workdir_path : string
        Path to the working directory.
    n_cores : int
        Maximum number of cores to be used in parallel run.

    Returns:
    --------
    """
    script_filepath = workdir_path + '/ecf-explorer/scripts/' \
    + 'run_parse_hhrepid.sh'

    hhrepid_out_dirpath = workdir_path + \
    '/ecf-explorer/input/annots/hhrepid'

    # set execute mode
    call('chmod a+x ' + script_filepath, shell=True)

    # run script
    run_cmd = 'nohup find {} -name "reprseq*.out" | xargs -P {} -n 1 {} \
    &'.format(hhrepid_out_dirpath, n_cores, script_filepath)
    call(run_cmd, shell=True)

def concatenate_parsing_hhrepid_results(workdir_path):
    """Check if all files were processed with parser and if yes then
    collect all the resulting dataframes into one and save it. If not all
    expected output files are present function quits.

    Parameters:
    -----------
    workdir_path : string
        Path to the working directory.

    Returns:
    --------
    bool
        Status of the execution. Returns False if still waiting for processing
        to complete. Returns True if process complete and files were
        successfuly concatenated.
    """
    # check if all expected output files are present
    hhrepid_out_dirpath = workdir_path + \
    '/ecf-explorer/input/annots/hhrepid'
    nb_expected_files  = len(glob.glob(hhrepid_out_dirpath + '/*.out'))
    nb_complete_files  = len(glob.glob(hhrepid_out_dirpath + '/*.csv'))

    if nb_expected_files == nb_complete_files:
        print('All files processed. Concatenating...')
        repeats = []
        for repeat_df in glob.glob(hhrepid_out_dirpath + '/*.csv'):
            repeats.append(pd.read_csv(repeat_df))
        repeats_all = pd.concat(repeats)
        repeats_all.to_csv(workdir_path + '/ecf-explorer/input/annots/' \
                           + 'hhrepid.txt', index=False)
        print('Done.')
        return True
    else:
        print('Not all files processed. Check again later.')
        return False

def clean_parse_hhrepid_partial_data(workdir_path):
    """Clean directory with partial parsed dataframes. Saves space.

    Parameters:
    -----------
    workdir_path : string
        Path to the working directory.

    Returns:
    --------
    """
    dir_path_single = workdir_path + '/ecf-explorer/input/annots/hhrepid/'
    if len(glob.glob(dir_path_single + '*.csv')) > 0:
        call('rm  ' + dir_path_single + '*.csv', shell=True)
    print('Cleaned single reprseq dataframes.')
